local case_index = 0
local total_cases = 12
local fail_count = 0
local stopped = false

function to_signed16(val)
	if val >= 0x8000 then
		return val - 0x10000
	else
		return val
	end
end

function diff(a, b)
	return math.abs(to_signed16(a) - to_signed16(b))
end

function writeCamera(idx)
	for i = 1, 9 do
		local val = input[idx * 9 + i]
		emu.writeWord(CAMERA + 2 * (i - 1), val, emu.memType.gsuWorkRam)
	end
end

function onTestSetup(address, value)
	print("Starting camera_lookAt test suite (12 cases)...")
	writeCamera(case_index)
end

function onTestStop(address, value)
	if stopped then return end

	local case_failed = false
	local base_exp = case_index * 16

	for i = 1, 16 do
		local read = emu.readWord(LOOKAT_MATRIX + 2 * (i - 1), emu.memType.gsuWorkRam, false)
		local exp = expected[base_exp + i]
		local d = diff(read, exp)
		local max_tol = 2
		-- Elements 4, 8, 12 are translation dot products scaled by eye coordinates (~64.0)
		-- where 1 LSB axis error propagates to ~64 LSBs
		if i == 4 or i == 8 or i == 12 then
			max_tol = 128
		end
		if d > max_tol then
			case_failed = true
			print(string.format("  [Case %d, element %d] FAILED: got 0x%04X, expected 0x%04X (diff %d, max tol %d)",
				case_index + 1, i, read, exp, d, max_tol))
		end
	end


	if not case_failed then
		print(string.format("  [%2d/12] PASSED: Case %d view matrix matches expected.", case_index + 1, case_index + 1))
	else
		fail_count = fail_count + 1
	end

	case_index = case_index + 1

	if case_index >= total_cases then
		stopped = true
		if fail_count == 0 then
			print("TEST PASSED: All 12 camera_lookAt tests passed.")
			emu.stop(0)
		else
			print(string.format("TEST FAILED: %d/12 cases failed.", fail_count))
			emu.stop(1)
		end
		return
	end

	writeCamera(case_index)
end

emu.addMemoryCallback(onTestSetup,
