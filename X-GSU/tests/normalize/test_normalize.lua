function compareAndLogOutput(address, value)
	--local read = emu.readWord(0x36A + 2*(index -1),emu.memType.gsuWorkRam,false)
	fail = 0

	emu.log("Checking")
	local readX = emu.readWord(NORMAL_OUT ,emu.memType.gsuWorkRam,false)
	local readY = emu.readWord(NORMAL_OUT + 2,emu.memType.gsuWorkRam,false)
	local readZ = emu.readWord(NORMAL_OUT + 4,emu.memType.gsuWorkRam,false)
	if readX ~= expected[index] then
		fail = 1
		emu.log(expected[index])
		emu.log(index)
		emu.log(string.format("Error lookat(%x) was %x expected %x", index,readX,expected[index]))
	end
	if readY ~= expected[index + 1] then
		fail = 1
		emu.log(expected[index + 1])
		emu.log(index + 1)
		emu.log(string.format("Error lookat(%x) was %x expected %x", index + 1,readY,expected[index + 1]))
	end
	if readZ ~= expected[index+2] then
		fail = 1
		emu.log(expected[index+2])
		emu.log(index+2)
		emu.log(string.format("Error lookat(%x) was %x expected %x", index+2,readZ,expected[index+2]))
	end

	if (fail ~= 0) then
		emu.log("Fail")
		emu.breakExecution()
	end

	if (fail == 0) then
		emu.log("Pass")
		emu.breakExecution()
	end

	index=index+3
	
end

