local index = 1
local fail_count = 0
local stopped = false

-- Helper to calculate difference handling signed or unsigned 16-bit
function diff(a, b)
	return math.abs(a - b)
end

function writeInput(idx)
	local v = input[idx]
	emu.writeWord(INPUT + 0, v[1], emu.memType.gsuWorkRam)
	emu.writeWord(INPUT + 2, v[2], emu.memType.gsuWorkRam)
	emu.writeWord(INPUT + 4, v[3], emu.memType.gsuWorkRam)
end

function onTestSetup(address, value)
	print("Starting vector3_normalize test suite (33 vectors)...")
	writeInput(index)
end

function onTestStop(address, value)
	if stopped then return end

	local rx = emu.readWord(NORMAL_OUT + 0, emu.memType.gsuWorkRam, false)
	local ry = emu.readWord(NORMAL_OUT + 2, emu.memType.gsuWorkRam, false)
	local rz = emu.readWord(NORMAL_OUT + 4, emu.memType.gsuWorkRam, false)
	local exp = expected[index]
	local vin = input[index]

	-- Allow 1 LSB fixed-point truncation tolerance
	local dx = diff(rx, exp[1])
	local dy = diff(ry, exp[2])
	local dz = diff(rz, exp[3])

	if dx <= 1 and dy <= 1 and dz <= 1 then
		print(string.format("  [%d/33] PASSED: (0x%04X, 0x%04X, 0x%04X) -> (0x%04X, 0x%04X, 0x%04X)",
			index, vin[1], vin[2], vin[3], rx, ry, rz))
	else
		print(string.format("  [%d/33] FAILED: got (0x%04X, 0x%04X, 0x%04X), expected (0x%04X, 0x%04X, 0x%04X) [diff: %d, %d, %d]",
			index, rx, ry, rz, exp[1], exp[2], exp[3], dx, dy, dz))
		fail_count = fail_count + 1
	end

	if index >= #input then
		stopped = true
		if fail_count == 0 then
			print("TEST PASSED: All 33 vector3_normalize tests passed.")
			emu.stop(0)
		else
			print(string.format("TEST FAILED: %d tests failed.", fail_count))
			emu.stop(1)
		end
		return
	end

	index = index + 1
	writeInput(index)
end

emu.addMemoryCallback(onTestSetup,
