package dev.secondsun.superx.tools.packer.model

/**
 * Generates ca65 compatible assembly include (.i) files describing the Texture Atlas.
 */
object AtlasIndexGenerator {

    fun generate(atlas: TextureAtlas, projectName: String = "TEXTURES"): String {
        val sanitizedProject = SourceTexture.sanitizeToIdentifier(projectName).uppercase()
        val guard = "__${sanitizedProject}_I_DEFINED__"

        val sb = StringBuilder()
        sb.appendLine(";; Auto-generated by SuperFX Texture Atlas Packer")
        sb.appendLine(";; Project: $projectName")
        sb.appendLine(";; Atlas: ${atlas.width}x${atlas.height} (${atlas.sizeBytes} bytes, 1 byte per texel)")
        sb.appendLine()
        sb.appendLine(".ifndef ::$guard")
        sb.appendLine("::$guard = 1")
        sb.appendLine()

        sb.appendLine(";; Structure for runtime texture lookup by IsoEngine / SuperFX")
        sb.appendLine(".struct texture_descriptor")
        sb.appendLine("    rom_offset    .word ; Base offset in atlas binary (Y * ATLAS_WIDTH + X)")
        sb.appendLine("    u_mask        .word ; (width - 1) bitmask")
        sb.appendLine("    v_mask        .word ; (height - 1) bitmask")
        sb.appendLine("    stride_shift  .word ; Shift to multiply v by atlas width")
        sb.appendLine(".endstruct")
        sb.appendLine()

        sb.appendLine(";; Atlas Dimensions & Constants")
        sb.appendLine("ATLAS_WIDTH        = ${atlas.width}")
        sb.appendLine("ATLAS_HEIGHT       = ${atlas.height}")
        sb.appendLine("ATLAS_SIZE_BYTES   = ${atlas.sizeBytes}")
        sb.appendLine("ATLAS_STRIDE_SHIFT = ${atlas.strideShift}")
        sb.appendLine()

        sb.appendLine(";; Per-Texture Symbolic Constants")
        for ((idx, tex) in atlas.textures.withIndex()) {
            val upperName = tex.name.uppercase()
            val byteOffset = idx * 8
            val romOffset = tex.y * atlas.width + tex.x

            sb.appendLine("TEXTURE_ID_$upperName = $idx")
            sb.appendLine("TEXTURE_${upperName}_BYTE_OFFSET = $byteOffset")
            sb.appendLine("TEXTURE_${upperName}_X = ${tex.x}")
            sb.appendLine("TEXTURE_${upperName}_Y = ${tex.y}")
            sb.appendLine("TEXTURE_${upperName}_WIDTH = ${tex.width}")
            sb.appendLine("TEXTURE_${upperName}_HEIGHT = ${tex.height}")
            sb.appendLine("TEXTURE_${upperName}_OFFSET = $romOffset")
            sb.appendLine("TEXTURE_${upperName}_U_MASK = ${tex.uMask}")
            sb.appendLine("TEXTURE_${upperName}_V_MASK = ${tex.vMask}")
            sb.appendLine("TEXTURE_${upperName}_WIDTH_SHIFT = ${tex.widthShift}")
            sb.appendLine()
        }

        sb.appendLine(";; Texture Table for runtime descriptor lookup")
        sb.appendLine("TEXTURE_TABLE:")
        for ((_, tex) in atlas.textures.withIndex()) {
            val romOffset = tex.y * atlas.width + tex.x
            sb.appendLine("    .word $romOffset, ${tex.uMask}, ${tex.vMask}, ${atlas.strideShift} ; ${tex.name}")
        }
        sb.appendLine()

        sb.appendLine(".endif ; $guard")
        return sb.toString()
    }
}

